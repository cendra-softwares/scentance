#!/usr/bin/env node
/**
 * Emit an idempotent SQL seed for the Scentance admin account.
 *
 * Usage:
 *   ADMIN_PASSWORD=... node scripts/seed-admin.mjs [out.sql]
 *
 * Then apply it remotely:
 *   npx wrangler d1 execute scentance-db --remote --file=.tmp/seed-admin.sql
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';

import { hashPassword } from 'better-auth/crypto';

const ADMIN_EMAIL = process.env.ADMIN_EMAIL ?? 'admin@gmail.com';
const ADMIN_NAME = 'Scentance Admin';
const ADMIN_PASSWORD = process.env.ADMIN_PASSWORD;

if (!ADMIN_PASSWORD || ADMIN_PASSWORD.length < 12) {
  console.error('Set ADMIN_PASSWORD to a value of at least 12 characters.');
  process.exit(1);
}

const sqlString = (value) => `'${String(value).replace(/'/g, "''")}'`;

const passwordHash = await hashPassword(ADMIN_PASSWORD);
const userId = randomUUID();
const accountId = 'seed-admin-credential';

const sql = `-- Scentance admin seed (generated by scripts/seed-admin.mjs)

INSERT INTO user (id, name, email, email_verified, created_at, updated_at)
VALUES (
  ${sqlString(userId)},
  ${sqlString(ADMIN_NAME)},
  ${sqlString(ADMIN_EMAIL)},
  1,
  unixepoch() * 1000,
  unixepoch() * 1000
)
ON CONFLICT(email) DO UPDATE SET
  name = excluded.name,
  email_verified = 1,
  updated_at = unixepoch() * 1000;

DELETE FROM account
WHERE provider_id = 'credential'
  AND user_id = (SELECT id FROM user WHERE email = ${sqlString(ADMIN_EMAIL)});

INSERT INTO account (id, account_id, provider_id, user_id, password, created_at, updated_at)
SELECT
  ${sqlString(accountId)},
  id,
  'credential',
  id,
  ${sqlString(passwordHash)},
  unixepoch() * 1000,
  unixepoch() * 1000
FROM user
WHERE email = ${sqlString(ADMIN_EMAIL)};

INSERT INTO profiles (id, email, role, is_guest, created_at, updated_at)
SELECT id, email, 'admin', 0, unixepoch() * 1000, unixepoch() * 1000
FROM user
WHERE email = ${sqlString(ADMIN_EMAIL)}
ON CONFLICT(id) DO UPDATE SET
  email = excluded.email,
  role = 'admin',
  is_guest = 0,
  updated_at = unixepoch() * 1000;
`;

const outputPath = path.resolve(process.argv[2] ?? '.tmp/seed-admin.sql');
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, sql, 'utf8');

console.log(`Wrote admin seed to ${outputPath}`);
console.log(`Email: ${ADMIN_EMAIL}`);
